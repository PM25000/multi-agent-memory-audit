def main():
    def offline(*args, **kwargs):
        raise RuntimeError('network_disabled_in_cached_reanalysis')

    with patch.object(socket.socket, 'connect', offline), patch.object(socket, 'create_connection', offline):
        raw, rows = dataset('test')
        old = read(FAIR/'analysis'/'summary.json')
        protected = [FAIR/'datasets'/'test.json', FAIR/'datasets'/'dev.json',
                     FAIR/'datasets'/'protocol.json', FAIR/'calibration.json', FAIR/'analysis'/'summary.json']
        protected += [FAIR/model/'cases'/f"{case['key']}.json" for model in MODELS for case in rows]
        before = {str(p.relative_to(ROOT)): digest(read(p)) for p in protected}
        result = {'version': 'contract-required-only-1', 'post_hoc_reanalysis': True,
                  'selection_rule': 'grade == 3', 'new_model_calls': 0,
                  'source_dataset_hash': digest(raw), 'n_inputs': len(rows),
                  'historical_endpoint_agreement': True, 'models': {}}
        if USE_RETRIES:
            from retry_contract_transport import load_completed_records, RETRY
            result.update(version='contract-required-only-transport-completed-2',
                          new_model_calls=read(RETRY/'manifest.json')['new_saved_responses'],
                          transport_retry_manifest=str(RETRY/'manifest.json'),
                          historical_endpoint_agreement='verified on original records before transport recovery')
        for model in MODELS:
            original_records = load_records(model, rows, raw)
            records = load_completed_records(model, rows, raw) if USE_RETRIES else original_records
            metrics = {m: [evaluate(c, r, m) for c, r in zip(rows, records)] for m in METHODS}
            baseline_metrics = ({m: [evaluate(c, r, m) for c, r in zip(rows, original_records)] for m in METHODS}
                                if USE_RETRIES and model == 'gpt55_responses' else metrics)
            endpoints = [fixed_all_memory_endpoint(c) for c in rows]
            diagnosis = {m: [field_error_diagnosis(c, metric, endpoint)
                             for c, metric, endpoint in zip(rows, metrics[m], endpoints)] for m in METHODS}
            splits = {}
            for split in ('all', 'multi', 'single', 'neutral'):
                indexes = [i for i, c in enumerate(rows) if split == 'all' or c['split'] == split]
                both = [i for i in indexes if all(not metrics[m][i]['method_output_failure'] for m in METHODS)]
                sr = {'all_inputs': compare(metrics, indexes), 'both_valid': compare(metrics, both),
                      'costs': summarize_costs([records[i] for i in indexes]),
                      'field_diagnosis': {m: summarize_field_diagnoses([diagnosis[m][i] for i in indexes]) for m in METHODS}}
                for method in METHODS:
                    historical = next(p for p in old['models'][model]['splits'][split]['curves'][method] if p['threshold'] == 3.0)
                    for key, value in summarize_metrics([baseline_metrics[method][i] for i in indexes]).items():
                        previous = historical[key]
                        assert value == previous or (isinstance(value, (int, float)) and isinstance(previous, (int, float))
                                                     and abs(value-previous) < 1e-10), (model, split, method, key, value, previous)
                splits[split] = sr
            result['models'][model] = {'splits': splits, 'record_hashes': {r['key']: digest(r) for r in records}}
            dump(DEST/'per_input'/f'{model}.json', {'metrics': metrics, 'field_diagnosis': diagnosis})
            print(json.dumps({'model': model, 'verified_cases': len(rows),
                              'multi_retention': {m: splits['multi']['all_inputs'][m]['P_available_macro'] for m in METHODS}}, ensure_ascii=False), flush=True)
        assert before == {str(p.relative_to(ROOT)): digest(read(p)) for p in protected}
        result['preserved_source_hashes'] = before
        dump(DEST/'summary.json', result)
        write_outputs(result)
        print(f'Verified {len(rows)*len(MODELS)} cached records; no model calls; output: {DEST}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--with-transport-retries', action='store_true')
    args = parser.parse_args()
    USE_RETRIES = args.with_transport_retries
    if USE_RETRIES:
        DEST = OUT / 'contract_required_only_retried_20260912'
    main()
