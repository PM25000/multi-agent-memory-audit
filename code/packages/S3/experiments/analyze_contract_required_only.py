def required_tasks(case, grades):
    entities = [e for e in case['entities'] if e['source'] == 'memory']
    indexes = [t['task_index'] for t in case['fixed_tasks']]
    validated = validate_grades({'tasks': grades}, indexes, len(entities))
    tasks = [{'name': fixed['name'], 'request_quotes': list(fixed['request_quotes']),
              'keep_entity_ids': [e['id'] for e, grade in zip(entities, row['grades']) if grade == 3]}
             for fixed, row in zip(case['fixed_tasks'], validated)]
    return tasks, indexes


def evaluate(case, record, method):
    status = record['method_status'][method]['status']
    if status != 'ok':
        assert record[f'{method}_tasks'] is None
        tasks, mapping = [], []
    else:
        tasks, mapping = required_tasks(case, record[f'{method}_tasks'])
    visible, unknown = build_visibility(case)
    identities = {id(t): i for t, i in zip(tasks, mapping)}

    def visibility(task, facts, ids, allow_unknown=False):
        i = identities[id(task)]
        return set(task['keep_entity_ids']) | visible[i] | (unknown[i] if allow_unknown else set())

    metric = score_visible(tasks, mapping, case['entities'], case['reference'], visibility)
    ceiling = score_visible(tasks, mapping, case['entities'], case['reference'],
                            lambda t, f, ids: visibility(t, f, ids, True))
    metric.update(memory_decomposition(tasks, mapping, case))
    metric.update(key=case['key'], split=case['split'], method_status=status,
                  method_output_failure=status != 'ok',
                  request_unknown_fact_recipient_pairs=sum(len(v) for v in unknown.values()) if tasks else 0,
                  request_unknown_could_change_fields=ceiling['correct']-metric['correct'],
                  P_available_lexical_ceiling=ceiling['P_available'],
                  L_all_upper_with_unknown=ceiling['L_all_upper'])
    if status != 'ok':
        assert metric['correct'] == 0 and metric['L_upper'] == 0
    return metric


def compare(metrics, indexes):
    selected = {m: [metrics[m][i] for i in indexes] for m in METHODS}
    assert [r['key'] for r in selected['joint']] == [r['key'] for r in selected['independent']]
    return {'n': len(indexes), 'keys': [r['key'] for r in selected['joint']],
            **{m: summarize_metrics(selected[m]) for m in METHODS},
            'paired': {k: paired_ci([r[k] for r in selected['joint']], [r[k] for r in selected['independent']])
                       for k in ('P_available', 'L_lower', 'L_upper', 'L_all_lower', 'L_all_upper')}}


def ci_text(row, key, scale=1):
    diff = row['paired'][key]
    lo, hi = diff['ci95']
    return f"{scale*diff['difference_joint_minus_independent']:+.2f} [{scale*lo:+.2f}, {scale*hi:+.2f}]"


